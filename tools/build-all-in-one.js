// Concatenates the backend into ONE file for a single paste into the Apps Script editor:
//   apps-script/ALL-IN-ONE.gs = Data, Code, Auth, Permits, Setup, DemoSeed, DemoAssets, Demo (this order)
// Usage: node tools/build-all-in-one.js   (the test suite fails when the file is out of date)
'use strict';
const fs = require('fs');
const path = require('path');

const ORDER = ['Data.gs', 'Code.gs', 'Auth.gs', 'Permits.gs', 'Setup.gs', 'DemoSeed.gs', 'DemoAssets.gs', 'Demo.gs'];
const dir = path.join(__dirname, '..', 'apps-script');

function build() {
  const head = '/**\n * e-Work Permit (DEMO) — ALL-IN-ONE backend. GENERATED by `node tools/build-all-in-one.js`\n' +
    ' * from apps-script/' + ORDER.join(', ') + ' (do not edit here).\n' +
    ' * Paste this whole file into ONE script file of a new Apps Script project, then run setupDemo() once.\n */\n';
  return head + ORDER.map((f) => '\n// ======================================================================== ' + f + '\n' +
    fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s+$/, '') + '\n').join('');
}

module.exports = { ORDER, build };

if (require.main === module) {
  const out = build();
  fs.writeFileSync(path.join(dir, 'ALL-IN-ONE.gs'), out);
  console.log('apps-script/ALL-IN-ONE.gs written (' + Math.round(out.length / 1024) + ' KB)');
}
